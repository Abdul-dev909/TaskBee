import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const systemPrompt = `You are Home Genie AI Assistant, a helpful and friendly assistant for the Home Genie platform - a marketplace connecting homeowners with local service providers.

Your capabilities include:
1. **Platform Support**: Answer questions about how Home Genie works, features, policies, and navigation
2. **Job Posting Help**: Help homeowners describe their service needs clearly and create effective job posts
3. **Provider Guidance**: Guide service providers through KYC verification, profile setup, and bidding on jobs
4. **Recommendations**: Suggest appropriate service categories based on user descriptions

Key Platform Information:
- Homeowners can post jobs, receive offers from providers, accept offers, and rate providers after completion
- Service providers must complete KYC verification (CNIC, selfie) before they can bid on jobs
- Jobs have categories: Plumbing, Electrical, Cleaning, Painting, AC Repair, Carpentry, etc.
- Providers can only see jobs matching their skill category and city
- Payment is handled after job completion with a platform fee

Tone: Friendly, professional, helpful. Keep responses concise but informative.
If you don't know something specific about the platform, be honest and suggest contacting support.

Always respond in the same language the user writes in.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    console.log("Processing AI assistant request with", messages.length, "messages");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please contact support." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      
      return new Response(JSON.stringify({ error: "AI service temporarily unavailable" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    console.log("Streaming AI response");
    
    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (error) {
    console.error("AI assistant error:", error);
    return new Response(JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
